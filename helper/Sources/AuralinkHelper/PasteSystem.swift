import AppKit
import ApplicationServices
import AuralinkHelperKit
import Carbon
import Foundation

// The platform side of textio.paste (PasteRunner, AuralinkHelperKit, does
// the steps): the clipboard in NSPasteboard, ⌘V and keys as posted events,
// the front app, and the focused element's value through Accessibility.

final class SystemPaste: PasteEnvironment, @unchecked Sendable {
    let front: FrontApps

    init(front: FrontApps) { self.front = front }

    func nowMs() -> Double { monotonicMs() }

    func sleep(ms: Double) async {
        guard ms > 0 else { return }
        try? await Task.sleep(nanoseconds: UInt64(ms * 1_000_000))
    }

    func frontApp() async -> App { await front.current() }

    func clipboardItems() async -> ClipboardItems {
        await onMain { Clipboard.snapshot(NSPasteboard.general) }
    }

    func writeClipboard(_ text: String) async -> Int {
        await onMain { () -> Int in
            let pb = NSPasteboard.general
            pb.clearContents()
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            // Clipboard managers skip these (nspasteboard.org).
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
            pb.writeObjects([item])
            return pb.changeCount
        }
    }

    func changeCount() async -> Int {
        await onMain { NSPasteboard.general.changeCount }
    }

    func restoreClipboard(_ items: ClipboardItems, unlessChangedFrom expected: Int) async -> Bool {
        await onMain { () -> Bool in
            let pb = NSPasteboard.general
            guard pb.changeCount == expected else { return false }
            Clipboard.restore(pb, items)
            return true
        }
    }

    func postCommandV() {
        postKeyEvent(UInt16(kVK_ANSI_V), flags: .maskCommand)
    }

    func postKey(_ key: KeyPress) {
        postKeyEvent(UInt16(clamping: key.key), flags: keyFlags(key.modifiers ?? []))
    }

    /// The focused element of pid through Accessibility (its value, the
    /// caret, its identity); nil when it cannot be read.
    func focusedValue(pid: Int) async -> FocusedValue? {
        let app = AXUIElementCreateApplication(pid_t(pid))
        AXUIElementSetMessagingTimeout(app, 0.25)
        var ref: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &ref) == .success,
              let ref, CFGetTypeID(ref) == AXUIElementGetTypeID() else { return nil }
        let e = ref as! AXUIElement
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(e, kAXValueAttribute as CFString, &v) == .success,
              let value = v as? String else { return nil }
        var sel: CFTypeRef?
        var caret = 0, length = 0
        if AXUIElementCopyAttributeValue(e, kAXSelectedTextRangeAttribute as CFString, &sel) == .success, let sel,
           CFGetTypeID(sel) == AXValueGetTypeID() {
            var r = CFRange()
            if AXValueGetValue(sel as! AXValue, .cfRange, &r) { caret = r.location; length = r.length }
        }
        return FocusedValue(element: Int(CFHash(e)), value: value, caret: caret, selectionLength: length)
    }
}

func keyFlags(_ modifiers: [String]) -> CGEventFlags {
    var f: CGEventFlags = []
    for m in modifiers {
        switch m {
        case "command": f.insert(.maskCommand)
        case "shift": f.insert(.maskShift)
        case "option": f.insert(.maskAlternate)
        case "control": f.insert(.maskControl)
        default: break
        }
    }
    return f
}

/// Posts one key press (down and up) at the HID level, marked as
/// Auralink's own (the event tap lets it through).
func postKeyEvent(_ key: UInt16, flags: CGEventFlags) {
    let src = CGEventSource(stateID: .hidSystemState)
    for down in [true, false] {
        guard let e = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: down) else { continue }
        e.flags = flags
        e.setIntegerValueField(.eventSourceUserData, value: injectedMarker)
        e.post(tap: .cghidEventTap)
    }
}

/// Every item of the clipboard with every type's data, to put it back.
/// Promised data (file promises) cannot be kept.
enum Clipboard {
    @MainActor static func snapshot(_ pb: NSPasteboard) -> ClipboardItems {
        (pb.pasteboardItems ?? []).map { item in
            var d: [String: Data] = [:]
            for t in item.types {
                if let data = item.data(forType: t) { d[t.rawValue] = data }
            }
            return d
        }
    }

    @MainActor static func restore(_ pb: NSPasteboard, _ snap: ClipboardItems) {
        pb.clearContents()
        guard !snap.isEmpty else { return }
        let items = snap.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (t, data) in types { item.setData(data, forType: NSPasteboard.PasteboardType(t)) }
            return item
        }
        pb.writeObjects(items)
    }
}
